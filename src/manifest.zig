// ── main ──────────────────────────────────────────────────────────────────────

pub fn main(init: std.process.Init) !void {
    const gpa = init.gpa;
    const io = init.io;

    var stdout_file_writer = Io.File.stdout().writer(io, &stdout_buf);
    var stdin_file_reader = Io.File.stdin().readerStreaming(io, &stdin_buf);
    const w = &stdout_file_writer.interface;
    const r = &stdin_file_reader.interface;

    try w.writeAll(
        \\acme-dns-aliyun manifest generator
        \\===================================
        \\
    );
    try w.flush();

    // ── shared fields ─────────────────────────────────────────────────────────

    const group_name = try gpa.dupe(u8, try prompt(w, r, "Webhook group name (e.g. acme.mycompany.com)"));
    defer gpa.free(group_name);

    const solver_name = try gpa.dupe(u8, try promptDefault(w, r, "Webhook solver name", "alidns"));
    defer gpa.free(solver_name);

    const image = try gpa.dupe(u8, try promptDefault(w, r, "Container image", "ghcr.io/dzvon/acme-dns-aliyun:main"));
    defer gpa.free(image);

    const email = try gpa.dupe(u8, try prompt(w, r, "Let's Encrypt account email"));
    defer gpa.free(email);

    // ── credential mode ───────────────────────────────────────────────────────

    const mode_idx = try promptChoice(w, r, "Credential mode", &.{ "accesskey", "rrsa" });

    const WebhookContent = union(enum) { accesskey: []u8, rrsa: []u8 };
    var webhook_content: WebhookContent = undefined;

    if (mode_idx == 0) {
        const ak_id = try prompt(w, r, "Access Key ID");
        const ak_secret = try prompt(w, r, "Access Key Secret");
        const region = try gpa.dupe(u8, try promptDefault(w, r, "Region", "cn-hangzhou"));
        defer gpa.free(region);

        const b64_id = try base64Encode(gpa, ak_id);
        defer gpa.free(b64_id);
        const b64_secret = try base64Encode(gpa, ak_secret);
        defer gpa.free(b64_secret);

        webhook_content = .{ .accesskey = try render(gpa, tmpl_webhook_accesskey, &.{
            .{ "{{BASE64_ACCESS_KEY_ID}}", b64_id },
            .{ "{{BASE64_ACCESS_KEY_SECRET}}", b64_secret },
            .{ "{{WEBHOOK_GROUP_NAME}}", group_name },
            .{ "{{WEBHOOK_SOLVER_NAME}}", solver_name },
            .{ "{{IMAGE}}", image },
            .{ "{{ALIBABA_CLOUD_REGION}}", region },
        }) };
    } else {
        const role_arn = try gpa.dupe(u8, try prompt(w, r, "RAM Role ARN (e.g. acs:ram::1234567890:role/cert-manager-dns-solver)"));
        defer gpa.free(role_arn);
        const oidc_arn = try gpa.dupe(u8, try prompt(w, r, "OIDC Provider ARN (e.g. acs:ram::1234567890:oidc-provider/ack-rrsa-abcdef)"));
        defer gpa.free(oidc_arn);
        const region = try gpa.dupe(u8, try promptDefault(w, r, "Region", "cn-hangzhou"));
        defer gpa.free(region);

        webhook_content = .{ .rrsa = try render(gpa, tmpl_webhook_rrsa, &.{
            .{ "{{WEBHOOK_GROUP_NAME}}", group_name },
            .{ "{{WEBHOOK_SOLVER_NAME}}", solver_name },
            .{ "{{IMAGE}}", image },
            .{ "{{ALIBABA_CLOUD_REGION}}", region },
            .{ "{{ALIBABA_CLOUD_ROLE_ARN}}", role_arn },
            .{ "{{ALIBABA_CLOUD_OIDC_PROVIDER_ARN}}", oidc_arn },
        }) };
    }
    defer switch (webhook_content) {
        inline else => |s| gpa.free(s),
    };

    // ── render shared templates ───────────────────────────────────────────────

    const api_content = try render(gpa, tmpl_apiservice, &.{
        .{ "{{WEBHOOK_GROUP_NAME}}", group_name },
    });
    defer gpa.free(api_content);

    const issuer_content = try render(gpa, tmpl_clusterissuer, &.{
        .{ "{{WEBHOOK_GROUP_NAME}}", group_name },
        .{ "{{WEBHOOK_SOLVER_NAME}}", solver_name },
        .{ "{{EMAIL_ADDRESS}}", email },
    });
    defer gpa.free(issuer_content);

    // ── write output files ────────────────────────────────────────────────────

    // The build system passes the output dir as argv[1].
    const args = try init.minimal.args.toSlice(init.arena.allocator());
    const out_dir_path: []const u8 = if (args.len > 1) args[1] else "zig-out/manifests";

    const cwd = Io.Dir.cwd();
    cwd.createDirPath(io, out_dir_path) catch |err| switch (err) {
        error.PathAlreadyExists => {},
        else => return err,
    };
    var out_dir = try cwd.openDir(io, out_dir_path, .{});
    defer out_dir.close(io);

    const webhook_filename = switch (webhook_content) {
        .accesskey => "webhook-accesskey.yaml",
        .rrsa => "webhook-rrsa.yaml",
    };
    const webhook_yaml = switch (webhook_content) {
        inline else => |s| s,
    };
    try out_dir.writeFile(io, .{ .sub_path = webhook_filename, .data = webhook_yaml });
    try out_dir.writeFile(io, .{ .sub_path = "apiservice.yaml", .data = api_content });
    try out_dir.writeFile(io, .{ .sub_path = "clusterissuer.yaml", .data = issuer_content });

    try w.print(
        \\
        \\Manifests written to {s}/
        \\  {s}
        \\  apiservice.yaml
        \\  clusterissuer.yaml
        \\
        \\Apply with:
        \\  kubectl apply -f {s}/{s}
        \\  kubectl apply -f {s}/apiservice.yaml
        \\  kubectl apply -f {s}/clusterissuer.yaml
        \\
    , .{
        out_dir_path, webhook_filename,
        out_dir_path, webhook_filename,
        out_dir_path, out_dir_path,
    });
    try w.flush();
}
