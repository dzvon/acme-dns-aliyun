/// Interactive generator for Kubernetes deployment manifests.
/// Run via:  zig build manifest
///
/// Prompts for credential mode and required values, then writes rendered YAML
/// files to zig-out/manifests/.
const std = @import("std");
const Io = std.Io;

var stdin_buf: [256]u8 = undefined;
var stdout_buf: [4096]u8 = undefined;

// ── prompt helpers ────────────────────────────────────────────────────────────

fn prompt(w: *Io.Writer, r: *Io.Reader, comptime label: []const u8) ![]const u8 {
    try w.print("{s}: ", .{label});
    try w.flush();
    const line = try r.takeDelimiter('\n') orelse return error.EndOfStream;
    return std.mem.trimEnd(u8, line, "\r");
}

fn promptDefault(w: *Io.Writer, r: *Io.Reader, comptime label: []const u8, default: []const u8) ![]const u8 {
    try w.print("{s} [{s}]: ", .{ label, default });
    try w.flush();
    const line = try r.takeDelimiter('\n') orelse return default;
    const trimmed = std.mem.trimEnd(u8, line, "\r");
    return if (trimmed.len == 0) default else trimmed;
}

fn promptChoice(w: *Io.Writer, r: *Io.Reader, comptime label: []const u8, comptime choices: []const []const u8) !usize {
    while (true) {
        try w.print("{s} (", .{label});
        for (choices, 0..) |c, i| {
            if (i > 0) try w.writeAll("/");
            try w.writeAll(c);
        }
        try w.writeAll("): ");
        try w.flush();
        const line = try r.takeDelimiter('\n') orelse return error.EndOfStream;
        const trimmed: []const u8 = std.mem.trimEnd(u8, line, "\r");
        for (choices, 0..) |c, i| {
            if (std.ascii.eqlIgnoreCase(trimmed, c)) return i;
        }
        try w.writeAll("  Please enter one of: ");
        for (choices, 0..) |c, i| {
            if (i > 0) try w.writeAll(", ");
            try w.writeAll(c);
        }
        try w.writeAll("\n");
    }
}

// ── template rendering ────────────────────────────────────────────────────────

fn render(allocator: std.mem.Allocator, template: []const u8, pairs: []const [2][]const u8) ![]u8 {
    var out: std.ArrayListUnmanaged(u8) = .empty;
    var src = template;
    while (src.len > 0) {
        var earliest_pos: usize = src.len;
        var earliest_pair: usize = pairs.len;
        for (pairs, 0..) |pair, i| {
            if (std.mem.indexOf(u8, src, pair[0])) |pos| {
                if (pos < earliest_pos) {
                    earliest_pos = pos;
                    earliest_pair = i;
                }
            }
        }
        if (earliest_pair == pairs.len) {
            try out.appendSlice(allocator, src);
            break;
        }
        try out.appendSlice(allocator, src[0..earliest_pos]);
        try out.appendSlice(allocator, pairs[earliest_pair][1]);
        src = src[earliest_pos + pairs[earliest_pair][0].len ..];
    }
    return out.toOwnedSlice(allocator);
}

fn base64Encode(allocator: std.mem.Allocator, s: []const u8) ![]u8 {
    const enc = std.base64.standard.Encoder;
    const len = enc.calcSize(s.len);
    const buf = try allocator.alloc(u8, len);
    _ = enc.encode(buf, s);
    return buf;
}

